const POINTS: Record<Difficulty, number> = { facil: 100, medio: 120, dificil: 150 };
const SECONDS: Record<Difficulty, number> = { facil: 15, medio: 18, dificil: 22 };

/** Posição da resposta certa fixa por id: varia entre perguntas, mas é igual no servidor e no navegador. */
function positionFor(id: string) {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;
  return h % 4;
}

function mcq(
  id: string,
  category: string,
  difficulty: Difficulty,
  prompt: string,
  answer: string,
  wrong: [string, string, string],
  explanation: string
): Activity {
  const correctIndex = positionFor(id);
  const options: string[] = [...wrong];
  options.splice(correctIndex, 0, answer);
  return {
    id,
    app: "info",
    category,
    type: "mcq",
    difficulty,
    prompt,
    options,
    correctIndex,
    explanation,
    points: POINTS[difficulty],
    timeSuggested: SECONDS[difficulty],
  };
}

function tf(
  id: string,
  category: string,
  difficulty: Difficulty,
  prompt: string,
  correctBool: boolean,
  explanation: string
): Activity {
  return {
    id,
    app: "info",
    category,
    type: "true-false",
    difficulty,
    prompt,
    correctBool,
    explanation,
    points: POINTS[difficulty] - 20,
    timeSuggested: SECONDS[difficulty] - 5,
  };
}

function order(
  id: string,
  category: string,
  difficulty: Difficulty,
  prompt: string,
  items: string[],
  explanation: string
): Activity {
  return {
    id,
    app: "info",
    category,
    type: "order",
    difficulty,
    prompt,
    items,
    explanation,
    points: POINTS[difficulty] + 30,
    timeSuggested: 30,
  };
}

